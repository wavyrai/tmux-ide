#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const zigIndex = args.indexOf("--zig");
const zig = zigIndex >= 0 ? args[zigIndex + 1] : "zig";
if (!zig || execFileSync(zig, ["version"], { encoding: "utf8" }).trim() !== "0.15.2")
  throw new Error("Terminal FNV artifact requires Zig 0.15.2; pass --zig PATH");
const temporary = mkdtempSync(join(tmpdir(), "tmux-ide-fnv-"));
try {
  const binary = join(temporary, "fnv.wasm");
  execFileSync(
    zig,
    [
      "cc",
      "-target",
      "wasm32-freestanding",
      "-O3",
      "-nostdlib",
      "-Wl,--no-entry",
      "-Wl,--strip-all",
      "-Wl,-z,stack-size=16384",
      "-Wl,--initial-memory=65536",
      "-Wl,--max-memory=65536",
      "-Wl,--export=update",
      "-Wl,--export=scratch_ptr",
      "-Wl,--export-memory",
      resolve(root, "scripts/native/terminal-fnv64.c"),
      "-o",
      binary,
    ],
    { stdio: "inherit" },
  );
  const bytes = [...readFileSync(binary)];
  const rows = [];
  for (let offset = 0; offset < bytes.length; offset += 20)
    rows.push(`  ${bytes.slice(offset, offset + 20).join(", ")},`);
  const source = `// Generated by scripts/build-terminal-fnv64.mjs with Zig 0.15.2.\n// Source: scripts/native/terminal-fnv64.c. No runtime filesystem dependency.\n// prettier-ignore\nexport const TERMINAL_FNV64_WASM_BYTES = new Uint8Array([\n${rows.join("\n")}\n]);\n`;
  const target = resolve(root, "packages/core/src/terminal-fnv64-wasm-bytes.ts");
  if (args.includes("--check")) {
    if (readFileSync(target, "utf8") !== source) throw new Error("Terminal FNV artifact is stale");
  } else writeFileSync(target, source);
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
