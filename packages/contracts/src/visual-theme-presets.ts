export const VISUAL_THEME_PRESETS: readonly VisualThemeDocumentV1[] = Object.entries(palettes).map(
  ([id, p]) => {
    const color = (hex: string) => ({
      space: "srgb" as const,
      red: parseInt(hex.slice(1, 3), 16),
      green: parseInt(hex.slice(3, 5), 16),
      blue: parseInt(hex.slice(5, 7), 16),
      alpha: 255,
    });
    const background = color(p.bg);
    const readable = (hex: string, surface: string) => {
      const candidate = color(hex);
      const backdrop = color(surface);
      const target = readableForeground(backdrop, color("#000000"), color("#ffffff"));
      for (let step = 0; step <= 20; step++) {
        const adjusted = mixSrgbColors(candidate, target, step / 20);
        if (contrastRatio(adjusted, backdrop) >= 4.5) return adjusted;
      }
      return target;
    };
    const appearance = background.red + background.green + background.blue > 450 ? "light" : "dark";
    return {
      version: 1,
      id,
      name: p.name,
      appearance,
      overrides: {
        surfaces: {
          canvas: background,
          terminal: background,
          panel: color(p.panel),
          panelRaised: color(p.header),
          header: color(p.header),
          headerActive: color(p.selected),
          command: color(p.panel),
        },
        text: {
          primary: color(p.text),
          secondary: color(p.textDim),
          muted: color(p.textDim),
          bright: color(p.textBright),
          link: readable(p.borderFocused, p.panel),
        },
        borders: {
          default: color(p.border),
          subtle: color(p.border),
          focused: color(p.borderFocused),
          selected: color(p.borderFocused),
          danger: color(p.negative),
          attention: color(p.warning),
        },
        statusTone: {
          neutral: color(p.neutral),
          info: color(p.borderFocused),
          warning: color(p.warning),
          danger: color(p.negative),
          success: color(p.positive),
        },
        selection: { selection: color(p.selected), selectionText: color(p.selectedText) },
      },
    };
  },
);
export function findVisualThemePreset(id: unknown): VisualThemeDocumentV1 | undefined {
  return typeof id === "string" ? VISUAL_THEME_PRESETS.find((p) => p.id === id) : undefined;
}
