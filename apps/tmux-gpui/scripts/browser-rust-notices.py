#!/usr/bin/env python3
"""Collect locked macOS browser-engine Cargo notices; preserve source notices too."""
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent

def render(evidence, lock):
    crates = [entry['package'] for entry in evidence['crates']]
    covered = {use['crate']['id'] for item in evidence['licenses'] for use in item['used_by']}
    if not crates or covered != {p['id'] for p in crates}:
        raise ValueError('Incomplete browser Cargo license coverage')
    if any(entry['license'] in ('Unknown', 'Ignore') for entry in evidence['crates']):
        raise ValueError('Unresolved browser Cargo license')
    spec = importlib.util.spec_from_file_location('native_notices', HERE.parent / 'upstream/scripts/release/generate-notices.py')
    helper = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(helper)
    sections = ['tmux-ide browser engine — Rust third-party notices',
        'Scope: locked aarch64-apple-darwin runtime dependency graph; build/dev dependencies excluded.',
        'Private workspace components are covered by the separately bundled Pixel and native SDK licenses.',
        'Generated by cargo-about 0.9.2; includes source notices and collected or canonical license texts.',
        'System libraries, Electron and non-Cargo assets are covered separately.',
        'Cargo.lock SHA-256: ' + hashlib.sha256(lock).hexdigest()]
    for item in evidence['licenses']:
        if not item['text'].strip(): raise ValueError('Empty browser license')
        sections += ['\n' + '=' * 72, item['name'] + ' (' + item['id'] + ')',
            'Used by: ' + ', '.join(use['crate']['name'] + '@' + use['crate']['version'] for use in item['used_by']), item['text']]
    for package in sorted(crates, key=lambda p: (p['name'], p['version'])):
        sections += ['\n' + '=' * 72, package['name'] + '@' + package['version'], 'Declared license: ' + str(package.get('license'))]
        if (package.get('source') or '').startswith('registry+'):
            sections += ['Source: https://crates.io/api/v1/crates/' + package['name'] + '/' + package['version'] + '/download']
        for name, text in helper.collect(package): sections += ['--- ' + name + ' ---', text]
    return '\n\n'.join(sections) + '\n'

def main():
    if len(sys.argv) != 3: raise SystemExit('Usage: browser-rust-notices.py PREPARED_BROWSER_SOURCE NEW_REPORT')
    source, output = map(Path, sys.argv[1:])
    lock = (source / 'pixel/engine/Cargo.lock').read_bytes()
    if subprocess.check_output(['cargo', 'about', '--version'], text=True).strip() != 'cargo-about 0.9.2':
        raise ValueError('cargo-about 0.9.2 required')
    with tempfile.TemporaryDirectory(prefix='browser-notices-') as temp:
        report = Path(temp) / 'evidence.json'
        subprocess.run(['cargo', 'about', 'generate', '--manifest-path', str(source / 'pixel/engine/Cargo.toml'),
            '--locked', '--format', 'json', '--config', str(HERE.parent / 'integrations/pixel/about.toml'),
            '--output-file', str(report)], check=True)
        text = render(json.loads(report.read_text()), lock)
    if (source / 'pixel/engine/Cargo.lock').read_bytes() != lock: raise ValueError('Browser lockfile changed')
    with output.open('x') as file: file.write(text)

if __name__ == '__main__': main()
